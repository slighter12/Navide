"""The G3 shell attempt runner: `tests/cli/g1eAttempt.ts` with ONE declared substitution (proposal H1: g3-named copies, the g1e file untouched and pinned).

Why (G3-r2 Phase A real-artifact check): `firstGenerationReceipts` accepts the E3 ready receipt only as `protocol: 'navide-acr', wire: 1, handoff: 'scm_rights'`. The backend speaks wire 2 at H, so the
unchanged runner rejects every Rust-arm ready receipt ("protocol/identity mismatch in ready receipt") whatever the sidecar does. Run 1 attributed that failure to the missing readyVersion; it was this.
The substitution changes the wire number the identity check demands (1 -> the backend's current `WIRE_VERSION`, 2); the check stays exactly as strict and no measured path changes.
The copy is GENERATED from the g1e file, so every other byte is the g1e byte; `check` proves that and is run by a test.
"""
from __future__ import annotations

from pathlib import Path

from agent_team_backend import cli_runtime_frames

SOURCE = "tests/cli/g1eAttempt.ts"
TARGET = "tests/cli/g3ShellAttempt.ts"
HEADER = ("// GENERATED by backend/tests/cli_regression/support/g3/attempt_copy.py from tests/cli/g1eAttempt.ts. Do not edit: `attempt_copy.check` compares this file with the g1e file and the declared substitution.\n"
          "// The only change: the E3 ready receipt identity expects the backend's current wire version (see attempt_copy.py).\n")
OLD_IDENTITY = "const identityOk = ready.protocol === 'navide-acr' && ready.wire === 1 && ready.handoff === 'scm_rights'"


def new_identity(wire: int | None = None) -> str:
    return OLD_IDENTITY.replace("ready.wire === 1", f"ready.wire === {cli_runtime_frames.WIRE_VERSION if wire is None else wire}")


def generate(root: Path, wire: int | None = None) -> str:
    source = (Path(root) / SOURCE).read_text(encoding="utf-8")
    if source.count(OLD_IDENTITY) != 1:
        raise ValueError("tests/cli/g1eAttempt.ts no longer has the wire-1 identity line exactly once: review the copy")
    return HEADER + source.replace(OLD_IDENTITY, new_identity(wire))


def write(root: Path) -> str:
    text = generate(root)
    (Path(root) / TARGET).write_text(text, encoding="utf-8")
    return text


def check(root: Path) -> list[str]:
    target = Path(root) / TARGET
    if not target.is_file():
        return [f"{TARGET} is missing"]
    return [] if target.read_text(encoding="utf-8") == generate(root) else [f"{TARGET} differs from the g1e file plus the declared substitution"]
